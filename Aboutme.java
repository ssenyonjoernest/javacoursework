public class Aboutme {

    public static void main(String[] args) {

        // Java's eight primitive data types
        int age = 23;
        double height = 1.75;
        boolean continuingStudent = true;
        char surnameInitial = 'S';
        long phoneNumber = 256708821166L;
        short numberOfCourses = 6;
        byte numberOfSiblings = 3;
        float weight = 68.5f;

        // Displaying each value using concatenation
        System.out.println("Age: " + age);
        System.out.println("Height in metres: " + height);
        System.out.println("Continuing student: " + continuingStudent);
        System.out.println("First letter of surname: " + surnameInitial);
        System.out.println("Phone number: " + phoneNumber);
        System.out.println("Number of courses: " + numberOfCourses);
        System.out.println("Number of siblings: " + numberOfSiblings);
        System.out.println("Weight in kilograms: " + weight);
    }
}